/** 生成「今日之前」的日期 */
function daysAgo(n) {
  return new Date(Date.now() - n * 24 * 60 * 60 * 1000);
}

/** 确保名称唯一：与既有名称及本批已用名称比对，冲突则追加 -N 后缀 */
function makeUniqueName(existingSet, baseName) {
  let name = baseName;
  let i = 2;
  while (existingSet.has(name)) {
    name = `${baseName}-${i}`;
    i += 1;
  }
  existingSet.add(name);
  return name;
}

